('WMS_PICKING_READ','WMS_PICKING_CREATE','WMS_PICKING_ASSIGN','WMS_PICKING_START','WMS_PICKING_CONFIRM')
WHERE r.role_code='TENANT_OWNER' AND r.is_system_role=1;
