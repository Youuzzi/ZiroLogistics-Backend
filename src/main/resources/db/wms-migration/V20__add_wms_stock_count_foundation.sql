INSERT INTO permissions(permission_code, module, description) VALUES
('WMS_STOCK_COUNT_READ','INVENTORY','Read tenant-scoped stock counts and count snapshots.'),
('WMS_STOCK_COUNT_CREATE','INVENTORY','Create stock counts and define warehouse location scopes.'),
('WMS_STOCK_COUNT_PLAN','INVENTORY','Validate and plan stock count location scopes.'),
('WMS_STOCK_COUNT_START','INVENTORY','Start a frozen stock count and capture the on-hand snapshot.'),
('WMS_STOCK_COUNT_RECORD','INVENTORY','Record physical stock count observations.'),
('WMS_STOCK_COUNT_SUBMIT','INVENTORY','Submit completed stock count results for review.'),
('WMS_STOCK_COUNT_REVIEW','INVENTORY','Review stock count results and variance evidence.'),
('WMS_STOCK_COUNT_APPROVE','INVENTORY','Approve reviewed stock count variances.'),
('WMS_STOCK_COUNT_CANCEL','INVENTORY','Cancel an eligible pre-submission stock count.');

INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.permission_code IN (
  'WMS_STOCK_COUNT_READ','WMS_STOCK_COUNT_CREATE','WMS_STOCK_COUNT_PLAN',
  'WMS_STOCK_COUNT_START','WMS_STOCK_COUNT_RECORD','WMS_STOCK_COUNT_SUBMIT',
  'WMS_STOCK_COUNT_REVIEW','WMS_STOCK_COUNT_APPROVE','WMS_STOCK_COUNT_CANCEL'
)
WHERE r.role_code = 'TENANT_OWNER' AND r.is_system_role = 1;
