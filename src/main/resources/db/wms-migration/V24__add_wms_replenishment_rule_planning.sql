INSERT INTO permissions(permission_code, module, description) VALUES
('WMS_REPLENISHMENT_READ','INVENTORY','Read tenant-scoped replenishment rules and tasks.'),
('WMS_REPLENISHMENT_RULE_MANAGE','INVENTORY','Create, update, deactivate and plan replenishment rules.'),
('WMS_REPLENISHMENT_TASK_CREATE','INVENTORY','Create replenishment tasks from eligible rules.');

INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.permission_code IN (
  'WMS_REPLENISHMENT_READ','WMS_REPLENISHMENT_RULE_MANAGE','WMS_REPLENISHMENT_TASK_CREATE'
)
WHERE r.role_code='TENANT_OWNER' AND r.is_system_role=1;
