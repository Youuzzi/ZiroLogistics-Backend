INSERT INTO permissions(permission_code, module, description) VALUES
('WMS_INVENTORY_ADJUSTMENT_READ','INVENTORY','Read tenant-scoped inventory adjustments and allocations.'),
('WMS_INVENTORY_ADJUSTMENT_CREATE','INVENTORY','Generate inventory adjustments from approved stock counts.'),
('WMS_INVENTORY_ADJUSTMENT_SUBMIT','INVENTORY','Submit inventory adjustments for independent approval.'),
('WMS_INVENTORY_ADJUSTMENT_APPROVE','INVENTORY','Approve inventory adjustments created by another membership.'),
('WMS_INVENTORY_ADJUSTMENT_REJECT','INVENTORY','Reject submitted inventory adjustments with a reason.'),
('WMS_INVENTORY_ADJUSTMENT_POST','INVENTORY','Post approved inventory adjustments through the inventory posting service.');

INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.permission_code IN (
  'WMS_INVENTORY_ADJUSTMENT_READ','WMS_INVENTORY_ADJUSTMENT_CREATE',
  'WMS_INVENTORY_ADJUSTMENT_SUBMIT','WMS_INVENTORY_ADJUSTMENT_APPROVE',
  'WMS_INVENTORY_ADJUSTMENT_REJECT','WMS_INVENTORY_ADJUSTMENT_POST'
)
WHERE r.role_code = 'TENANT_OWNER' AND r.is_system_role = 1;