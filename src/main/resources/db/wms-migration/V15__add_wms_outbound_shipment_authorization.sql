INSERT INTO permissions (permission_code, module, description) VALUES
  ('WMS_INVENTORY_RESERVE', 'INVENTORY', 'Reserve and release available inventory through controlled workflows.'),
  ('WMS_OUTBOUND_SHIPMENT_READ', 'WAREHOUSE', 'Read tenant outbound shipments.'),
  ('WMS_OUTBOUND_SHIPMENT_CREATE', 'WAREHOUSE', 'Create tenant outbound shipment drafts.'),
  ('WMS_OUTBOUND_SHIPMENT_UPDATE', 'WAREHOUSE', 'Add lines to editable outbound shipment drafts.'),
  ('WMS_OUTBOUND_SHIPMENT_ALLOCATE', 'WAREHOUSE', 'Allocate and reserve stock for outbound shipment lines.'),
  ('WMS_OUTBOUND_SHIPMENT_RELEASE', 'WAREHOUSE', 'Release fully allocated outbound shipments for picking.');

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p
  ON p.permission_code IN (
    'WMS_INVENTORY_RESERVE',
    'WMS_OUTBOUND_SHIPMENT_READ', 'WMS_OUTBOUND_SHIPMENT_CREATE',
    'WMS_OUTBOUND_SHIPMENT_UPDATE', 'WMS_OUTBOUND_SHIPMENT_ALLOCATE',
    'WMS_OUTBOUND_SHIPMENT_RELEASE'
  )
WHERE r.role_code = 'TENANT_OWNER' AND r.is_system_role = 1;
